using System.Reflection;
using System.Text;
using System.Text.Json;

namespace VoiceCtrl.Tools.BridgeTypegen;

/// <summary>
/// Writes <c>ui/src/bridge/contracts.g.ts</c> from a <see cref="ContractCatalog"/>. The output
/// mirrors <c>BridgeJsonContext</c>'s wire format: camelCase properties, enums as camelCase string
/// unions, nullable members as <c>T | null</c>. Line endings are always <c>\n</c>, so the
/// freshness test compares text, not platforms.
/// </summary>
public static class TypeScriptWriter
{
    private static readonly NullabilityInfoContext Nullability = new();

    public static string Write(ContractCatalog catalog)
    {
        var ts = new StringBuilder();
        ts.Append("// Generated by tools/BridgeTypegen from the [BridgeCommand] and [BridgeEvent] records in\n");
        ts.Append("// src/VoiceCtrl.Core/Bridge. Do not edit or hand-merge: change the C# records, then run\n");
        ts.Append("// `dotnet run --project tools/BridgeTypegen`.\n");

        foreach (Type type in catalog.AllTypes.Where(t => t.IsEnum))
        {
            string members = string.Join(" | ", Enum.GetNames(type).Select(n => $"\"{Camel(n)}\""));
            ts.Append($"\nexport type {type.Name} = {members};\n");
        }

        foreach (Type type in catalog.AllTypes.Where(t => !t.IsEnum))
        {
            PropertyInfo[] properties = [.. ContractCatalog.WireProperties(type)];
            if (properties.Length == 0)
            {
                ts.Append($"\nexport type {type.Name} = Record<string, never>;\n");
                continue;
            }

            ts.Append($"\nexport interface {type.Name} {{\n");
            foreach (PropertyInfo property in properties)
            {
                ts.Append($"  {Camel(property.Name)}: {TypeOf(property)};\n");
            }

            ts.Append("}\n");
        }

        ts.Append("\n/** Command name → its arguments and the value the host answers with. */\n");
        ts.Append("export interface BridgeCommands {\n");
        foreach (CommandContract command in catalog.Commands)
        {
            ts.Append($"  \"{command.Name}\": {{ args: {command.Args.Name}; result: {command.Result?.Name ?? "null"} }};\n");
        }

        ts.Append("}\n");

        ts.Append("\n/** Event name → its payload. Events carry only changes after the snapshot. */\n");
        ts.Append("export interface BridgeEvents {\n");
        foreach (EventContract bridgeEvent in catalog.Events)
        {
            ts.Append($"  \"{bridgeEvent.Name}\": {bridgeEvent.Payload.Name};\n");
        }

        ts.Append("}\n");
        ts.Append("\nexport type CommandName = keyof BridgeCommands;\n");
        ts.Append("export type EventName = keyof BridgeEvents;\n");
        return ts.ToString();
    }

    private static string TypeOf(PropertyInfo property)
    {
        NullabilityInfo nullability = Nullability.Create(property);
        string type = TypeOf(property.PropertyType, nullability);
        return nullability.ReadState == NullabilityState.Nullable ? $"{type} | null" : type;
    }

    private static string TypeOf(Type type, NullabilityInfo nullability)
    {
        type = Nullable.GetUnderlyingType(type) ?? type;

        if (ContractCatalog.ElementType(type) is { } element)
        {
            NullabilityInfo? elementNullability = nullability.ElementType ?? nullability.GenericTypeArguments.FirstOrDefault();
            string elementType = elementNullability is null ? TypeOf(element, nullability) : TypeOf(element, elementNullability);
            bool elementNullable = elementNullability?.ReadState == NullabilityState.Nullable;
            return elementNullable ? $"({elementType} | null)[]" : $"{elementType}[]";
        }

        if (type == typeof(bool))
        {
            return "boolean";
        }

        if (type == typeof(string) || type == typeof(DateTimeOffset) || type == typeof(DateTime) || type == typeof(Guid))
        {
            return "string";
        }

        return type.IsPrimitive || type == typeof(decimal) ? "number" : type.Name;
    }

    private static string Camel(string name) => JsonNamingPolicy.CamelCase.ConvertName(name);
}
